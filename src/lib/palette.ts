/**
 * ชุดสีเชิงหมวดหมู่ — ผ่านการตรวจด้วยเครื่องมือแล้ว ไม่ใช่เลือกด้วยตา
 *
 * ใช้ตอนที่สีทำหน้าที่ "บอกว่านี่คือใคร" (เช่น ค่ายผู้ให้บริการ)
 * ถ้าสีทำหน้าที่บอก "มากหรือน้อย" ให้ใช้สีเดียวไล่เข้ม-อ่อนแทน อย่าใช้ไฟล์นี้
 *
 * ผลตรวจคู่ slot 1–2 (น้ำเงิน/ส้ม) บนพื้นของธีมทั้งสองโหมด:
 *   CVD ΔE            24.7 สว่าง · 26.8 มืด   (เกณฑ์ ≥ 8)
 *   normal-vision ΔE  33.6 สว่าง · 31.8 มืด   (เกณฑ์ ≥ 15)
 *   contrast กับพื้น   ผ่านทั้งคู่ (≥ 3:1)
 *
 * ── กฎที่ห้ามฝ่าฝืน ─────────────────────────────────────────────
 * 1. จ่ายสีตาม "ตัวตน" ไม่ใช่ตามลำดับที่ query คืนมา — ค่ายไหนได้ slot ไหน
 *    เก็บไว้ในฐานข้อมูล (operators.color_slot) ถ้าไล่ตามลำดับ พอกรองค่ายหนึ่งออก
 *    อีกค่ายจะเปลี่ยนสี แล้วคนที่จำสีไว้จะอ่านผิด
 * 2. เกิน 8 หมวดห้ามสร้างสีใหม่ — ให้ยุบหางเป็น "อื่น ๆ" แทน
 *    สีที่ 9 จะแยกจากสีเดิมไม่ออกภายใต้ภาวะตาบอดสีเสมอ
 * 3. สีต้องไม่ใช่ช่องทางสื่อความหมายช่องเดียว — ต้องมี legend หรือป้ายกำกับคู่เสมอ
 */

const LIGHT = [
  '#2a78d6', // 1 น้ำเงิน
  '#eb6834', // 2 ส้ม
  '#1baf7a', // 3 เขียวอมฟ้า
  '#eda100', // 4 เหลือง
  '#e87ba4', // 5 ชมพู
  '#008300', // 6 เขียว
  '#4a3aa7', // 7 ม่วง
  '#e34948', // 8 แดง
] as const

const DARK = [
  '#3987e5', '#d95926', '#199e70', '#c98500',
  '#d55181', '#008300', '#9085e9', '#e66767',
] as const

/** สีของสิ่งที่ยังไม่รู้ค่า — เทากลาง ไม่ใช่ slot ใดใน 8 สีข้างบน */
export const UNKNOWN_COLOR = { light: '#8a8f98', dark: '#6b727d' } as const

/**
 * @param slot 1–8 ตามที่เก็บไว้กับตัวตนนั้น ๆ · เกินช่วงจะวนกลับ slot 1
 *             (ไม่ควรเกิดขึ้น — ถ้าเกิดแปลว่ามีหมวดเกิน 8 ต้องยุบเป็น "อื่น ๆ" ก่อน)
 */
export function categorical(slot: number | null | undefined, dark: boolean): string {
  if (slot === null || slot === undefined) return dark ? UNKNOWN_COLOR.dark : UNKNOWN_COLOR.light
  const list = dark ? DARK : LIGHT
  return list[(slot - 1) % list.length] ?? list[0]
}
